// Fluxo público real, com dados sintéticos, sem .env ou envios externos.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { chromium, expect } = require('@playwright/test');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-precheckin-'));
process.chdir(temp);
process.env.NODE_ENV = 'test';
process.env.DB_PATH = ':memory:';
process.env.EMAIL_ENABLED = 'false';
process.env.FRONTEND_PATH = path.resolve(__dirname, '../../../frontend');
const app = require('../app');
const { db } = require('../config/database');
let server, browser;

async function main() {
  db.exec(`INSERT INTO organizations (id,name,slug) VALUES ('org','Alojamento de teste','qa');
    INSERT INTO accommodations (id,organization_id,name,type,price_per_night,max_guests,checkin_time,rgpd_text)
    VALUES ('acc','org','Casa da Oliveira','alojamento',120,4,'15:30','<p>Política de privacidade &amp; dados pessoais.</p>');
    INSERT INTO guests (id,organization_id,name,email,nationality)
    VALUES ('guest','org','Marta Silva','marta@example.invalid','Espanha');
    INSERT INTO reservations (id,organization_id,guest_id,accommodation_id,check_in,check_out,nights,num_guests,num_adults,num_children,total_amount,status,precheckin_token,guests_data)
    VALUES ('res','org','guest','acc','2035-06-10','2035-06-14',4,2,1,1,480,'confirmada','qa-publico','[{"name":"Leonor Silva","nationality":"Espanha","birth_date":"2020-05-12"}]');`);
  server = app.listen(0, '127.0.0.1');
  await new Promise((resolve, reject) => { server.once('listening', resolve); server.once('error', reject); });
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, serviceWorkers: 'block' });
  // Evita que fontes externas atrasem a validação funcional.
  await context.route('https://**/*', route => route.abort());
  const page = await context.newPage();
  page.setDefaultTimeout(6000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const url = `http://127.0.0.1:${server.address().port}/pre-checkin/qa-publico`;
  await page.goto(url);
  await expect(page.locator('#pc-next')).toBeEnabled();
  await expect(page.locator('#pc-summary-photo')).toBeHidden();
  await expect(page.locator('#pc-progress button')).toHaveCount(3);
  const mainCard = page.locator('[data-guest="0"]');
  const child = page.locator('[data-guest="1"]');
  await expect(child).toBeHidden();
  await page.locator('#pc-next').click();
  await expect(mainCard.locator('[data-field="birth_date"]')).toBeFocused();
  await expect(mainCard.locator('[aria-invalid="true"]')).not.toHaveCount(0);
  await mainCard.locator('[data-field="birth_date"]').fill('31-02-1990');
  await page.locator('#pc-next').click();
  await expect(mainCard.locator('[data-field="birth_date"]')).toHaveAttribute('aria-invalid', 'true');
  await mainCard.locator('[data-field="birth_date"]').fill('03-02-1990');
  const nationality = mainCard.locator('[data-field="nationality"]');
  await nationality.fill('PT');
  await nationality.press('ArrowDown');
  await nationality.press('Enter');
  await expect(nationality).toHaveValue('Portugal');
  await expect(mainCard.locator('[data-field="document_number"]')).toBeHidden();
  await nationality.fill('Espanha');
  await nationality.press('Enter');
  await expect(mainCard.locator('[data-field="document_number"]')).toBeVisible();
  const residence = mainCard.locator('[data-field="residence_country"]');
  await residence.fill('franca');
  await residence.press('ArrowDown');
  await residence.press('Enter');
  await expect(residence).toHaveValue('França');
  await residence.fill('fra');
  await mainCard.getByRole('option', { name: 'França', exact: true }).click();
  await expect(residence).toHaveValue('França');
  await mainCard.locator('[data-field="document_type"]').selectOption('passport');
  await mainCard.locator('[data-field="document_number"]').fill('AB12345');
  await mainCard.locator('[data-copy-nationality]').click();
  await expect(mainCard.locator('[data-field="document_issuer_country"]')).toHaveValue('Espanha');
  await mainCard.locator('.pc-company-toggle').click();
  await page.locator('#pc-next').click();
  await expect(mainCard.locator('[data-field="company"]')).toBeFocused();
  await mainCard.locator('[data-field="company"]').fill('Empresa de teste');
  await mainCard.locator('[data-field="company_nif"]').fill('500000000');
  await page.locator('#pc-next').click();
  await expect(child).toBeVisible();
  await child.locator('[data-copy-residence]').click();
  await expect(child.locator('[data-field="residence_country"]')).toHaveValue('França');
  await child.locator('[data-field="document_type"]').selectOption('passport');
  await child.locator('[data-field="document_number"]').fill('CH12345');
  await child.locator('[data-copy-nationality]').click();
  await child.locator('[data-complete-guest]').click();
  await expect(child.locator('.pc-guest-status')).toHaveText('Completo');
  await page.locator('#pc-back').click();
  await expect(mainCard.locator('[data-field="document_number"]')).toHaveValue('AB12345');
  await page.screenshot({ path: path.join(temp, 'desktop.png'), fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(temp, 'mobile.png'), fullPage: true, animations: 'disabled' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('#pc-next').click();
  await page.locator('#pc-next').click();
  await expect(page.locator('#pc-time-presets button')).toHaveCount(6);
  await page.locator('#pc-submit').click();
  await expect(page.locator('#pc-arrival-time')).toBeFocused();
  await page.locator('#pc-arrival-time').fill('25:99');
  await page.locator('#pc-submit').click();
  await expect(page.locator('#pc-arrival-time')).toHaveValue('25:99');
  await expect(page.locator('#pc-arrival-time')).toHaveAttribute('aria-invalid', 'true');
  await page.getByRole('button', { name: '17:30', exact: true }).click();
  await expect(page.getByRole('button', { name: '17:30', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByText('Política de privacidade do alojamento', { exact: true }).click();
  await expect(page.locator('#pc-privacy-text')).toHaveText('Política de privacidade & dados pessoais.');
  await page.locator('#pc-rgpd').check();
  await expect(page.locator('#pc-error')).toBeHidden();
  await page.screenshot({ path: path.join(temp, 'confirmacao.png'), fullPage: true, animations: 'disabled' });
  await page.locator('#pc-submit').click();
  await expect(page.locator('#pc-success')).toContainText('sucesso');
  assert.equal(db.prepare('SELECT arrival_time FROM reservations WHERE id=?').get('res').arrival_time, '17:30');
  assert.equal(db.prepare('SELECT document_number FROM guests WHERE id=?').get('guest').document_number, 'AB12345');
  await page.reload();
  await expect(page.locator('#pc-edit-note')).toContainText('Já enviou');
  await expect(mainCard.locator('[data-field="company"]')).toHaveValue('Empresa de teste');
  await mainCard.locator('.pc-company-toggle').click();
  await page.locator('#pc-next').click();
  await page.locator('#pc-next').click();
  await page.locator('#pc-rgpd').check();
  await page.locator('#pc-submit').click();
  await expect(page.locator('#pc-success')).toContainText('Alterações guardadas');
  assert.equal(db.prepare('SELECT company FROM guests WHERE id=?').get('guest').company, null);
  assert.equal(db.prepare('SELECT company_nif FROM guests WHERE id=?').get('guest').company_nif, null);
  await page.reload();
  await expect(mainCard.locator('[data-field="is_company"]')).not.toBeChecked();
  // Reserva individual: duas etapas e país normalizado a partir do código ISO.
  db.exec("UPDATE reservations SET num_guests=1,num_adults=1,num_children=0,guests_data='[]' WHERE id='res'; UPDATE guests SET nationality='PT' WHERE id='guest'");
  await page.reload();
  await expect(page.locator('#pc-progress button')).toHaveCount(2);
  await expect(nationality).toHaveValue('Portugal');
  await expect(mainCard.locator('[data-field="document_number"]')).toBeHidden();
  await page.setViewportSize({ width: 320, height: 640 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 844, height: 390 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log(`OK: etapas, países, validação, submissão, reabertura e layouts. Capturas: ${temp}`);
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  await browser?.close();
  if (server) await new Promise(resolve => server.close(resolve));
  db.close();
});
