// Interface real e dados descartáveis; não lê a configuração nem a BD de produção.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { chromium, expect } = require('@playwright/test');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-vouchers-browser-'));
const previous = process.cwd();
process.chdir(temp);
process.env.DB_PATH = ':memory:';
process.env.NODE_ENV = 'test';
process.env.EMAIL_ENABLED = 'false';
process.env.FRONTEND_PATH = path.resolve(__dirname, '../../../frontend');
const app = require('../app');
const { db } = require('../config/database');
const auth = require('../services/authService');
const orgs = require('../services/orgService');
const { redeemVoucher } = require('../services/voucherService');
const artifacts = process.env.BROWSER_ARTIFACTS_DIR || path.join(os.tmpdir(), 'sp-vouchers-preview');
let server, browser;
async function main() {
  const org = orgs.createOrganization('Vouchers de teste');
  const user = auth.createUser({ name: 'Teste', email: 'vouchers@example.invalid', password: 'SyntheticBrowser123!' });
  orgs.createMembership({ organizationId: org.id, userId: user.id, role: 'owner' });
  const session = auth.createSession(user.id, org.id).sessionId;
  db.prepare(`INSERT INTO accommodations(id,organization_id,name,type,price_per_night,max_guests)
    VALUES ('unit',?,'Suite de teste','alojamento',100,4)`).run(org.id);
  db.prepare(`INSERT INTO guests(id,organization_id,name,email) VALUES ('guest',?,'Hóspede de teste','guest@example.invalid')`).run(org.id);
  for (let i = 1; i <= 3; i++) db.prepare(`INSERT INTO reservations
    (id,organization_id,guest_id,accommodation_id,check_in,check_out,nights,num_guests,total_amount,status)
    VALUES (?,?,'guest','unit','2035-01-01','2035-01-03',2,1,200,'confirmada')`).run(`SP-TESTE-${i}`, org.id);
  server = app.listen(0, '127.0.0.1');
  await new Promise((resolve, reject) => { server.once('listening', resolve); server.once('error', reject); });
  const base = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' });
  await context.addCookies([{ name: auth.SESSION_COOKIE, value: session, url: base }]);
  const page = await context.newPage();
  page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.locator('[data-view="vouchers"]').click();
  await page.locator('#view-vouchers').getByRole('button', { name: 'Novo Voucher' }).click();
  await expect(page.locator('#v-max-uses')).toHaveValue('1');
  await page.locator('#v-code').fill('DEZVEZES');
  await page.locator('#v-value').fill('10');
  await page.getByLabel('Limite de utilizações').fill('0');
  await page.locator('#v-save-btn').click();
  await expect(page.locator('#v-max-uses-error')).toContainText('igual ou superior a 1');
  await page.getByLabel('Limite de utilizações').fill('10');
  await page.locator('#v-save-btn').click();
  await expect(page.locator('#voucher-modal-bg')).not.toHaveClass(/open/);
  await expect(page.locator('.vouchers-desktop')).toContainText('0 / 10');
  const voucher = db.prepare("SELECT * FROM vouchers WHERE code='DEZVEZES'").get();
  for (let i = 1; i <= 3; i++) redeemVoucher(org.id, voucher.id, `SP-TESTE-${i}`, 20);
  db.prepare("UPDATE reservations SET status='cancelada' WHERE id='SP-TESTE-2'").run();
  db.prepare("DELETE FROM reservations WHERE id='SP-TESTE-3'").run();
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('[data-view="vouchers"]').click();
  await expect(page.locator('.vouchers-desktop')).toContainText('3 / 10');
  fs.mkdirSync(artifacts, { recursive: true });
  await page.screenshot({ path: path.join(artifacts, 'desktop-list.png'), fullPage: true, animations: 'disabled' });
  await page.locator('.vouchers-desktop').getByRole('button', { name: 'Ver reservas' }).click();
  await expect(page.locator('.voucher-history-item')).toHaveCount(3);
  await expect(page.locator('#voucher-history-summary')).toContainText('3 de 10');
  await expect(page.locator('#voucher-history-list')).toContainText('Reserva eliminada');
  await expect(page.locator('#voucher-history-list')).toContainText('cancelada');
  await page.screenshot({ path: path.join(artifacts, 'desktop-history.png'), fullPage: true, animations: 'disabled' });
  await page.locator('#voucher-history-list').getByRole('button', { name: 'Ver reserva' }).first().click();
  await expect(page.locator('#voucher-history-modal-bg')).not.toHaveClass(/open/);
  await expect(page.locator('#reserva-detail-page')).toBeVisible();
  await page.getByRole('button', { name: 'Voltar', exact: true }).click();
  await page.locator('[data-view="vouchers"]').click();
  await page.locator('.vouchers-desktop [data-on-click="vouchers-open-voucher-modal-36eda97"]').click();
  await expect(page.locator('#v-max-uses')).toHaveValue('10');
  await page.getByLabel('Limite de utilizações').fill('2'); await page.locator('#v-save-btn').click();
  await expect(page.locator('#v-max-uses-error')).toContainText('igual ou superior a 3');
  await page.getByLabel('Limite de utilizações').fill('3'); await page.locator('#v-save-btn').click();
  await expect(page.locator('.vouchers-desktop')).toContainText('Esgotado');
  await page.locator('.vouchers-desktop [data-on-click="vouchers-open-voucher-modal-36eda97"]').click();
  await page.getByLabel('Limite de utilizações').fill('10'); await page.locator('#v-save-btn').click();
  await expect(page.locator('.vouchers-desktop')).toContainText('Ativo');

  await page.setViewportSize({ width: 375, height: 812 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(page.locator('.vouchers-mobile')).toContainText('Utilizações: 3 / 10');
  await expect(page.locator('.toast')).toHaveCount(0, { timeout: 10000 });
  await page.locator('.vouchers-mobile').getByRole('button', { name: 'Ver reservas' }).click();
  await expect(page.locator('.voucher-history-item')).toHaveCount(3);
  await page.locator('#voucher-history-modal-bg .modal-footer').getByRole('button', { name: 'Fechar', exact: true }).click({ trial: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.screenshot({ path: path.join(artifacts, 'mobile-history.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Fechar lista de reservas' }).click();
  await page.locator('.vouchers-mobile').getByRole('button', { name: 'Editar', exact: true }).click();
  await expect(page.getByLabel('Limite de utilizações')).toHaveValue('10');
  await page.getByLabel('Limite de utilizações').scrollIntoViewIfNeeded();
  await expect(page.getByLabel('Limite de utilizações')).toBeInViewport();
  await page.locator('#v-save-btn').click({ trial: true });
  await page.screenshot({ path: path.join(artifacts, 'mobile-form.png'), fullPage: true, animations: 'disabled' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 812, height: 375 });
  await page.locator('.vouchers-desktop').getByRole('button', { name: 'Ver reservas' }).click();
  await expect(page.locator('.voucher-history-item')).toHaveCount(3);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('Vouchers: criar/editar limite, validação, contagem, esgotamento, reativação, histórico e abertura de reserva verificados em desktop e mobile.');
  console.log(`Capturas: ${artifacts}`);
}
main().catch(async error => {
  console.error(error); process.exitCode = 1;
  fs.mkdirSync(artifacts, { recursive: true });
  const page = browser?.contexts()[0]?.pages()[0];
  if (page) await page.screenshot({ path: path.join(artifacts, 'failure.png'), fullPage: true, animations: 'disabled' }).catch(() => {});
}).finally(async () => {
  if (browser) await browser.close();
  if (server) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
  db.close(); process.chdir(previous); fs.rmSync(temp, { recursive: true, force: true });
});
